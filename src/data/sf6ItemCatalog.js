const catalogItem = (id, name, category, description, usage, weight, mechanics = {}) => ({
  id: `sf6_item_${id}`, name, category, description, usage, weight, quantity: 1, ownerId: 'WORLD',
  ...(category.includes('消耗品') || category === '补给食品' ? { consumable: true, infinite: true } : {}),
  ...mechanics
});

const food = (id, name, calories, weight, description) => catalogItem(
  id, name, '补给食品', description,
  `在长休结算时作为队伍共享口粮消耗；每份提供 ${calories} kcal。每名参与长休的玩家角色默认需要 1500 kcal，系统会从所选角色背包中自动扣除足量份数。`,
  weight, { calories }
);
const recovery = (id, name, weight, effectValue, description, usage = '附赠动作使用；使用后从角色背包扣除 1 份。') => catalogItem(id, name, '恢复消耗品', description, usage, weight, { effectValue });
const tactical = (id, name, weight, effectValue, description, usage) => catalogItem(id, name, '战术消耗品', description, usage, weight, { effectValue });
const armor = (id, name, weight, acBonus, description, usage) => catalogItem(id, name, '防具', description, usage, weight, { acBonus });
const weapon = (id, name, weight, diceCount, die, fixed, damageType, description, usage) => catalogItem(id, name, '武器', description, usage, weight, { damageDiceCount: diceCount, damageDie: die, damageFixed: fixed, damageType });
const gear = (id, name, category, weight, effectValue, description, usage, extra = {}) => catalogItem(id, name, category, description, usage, weight, { effectValue, ...extra });

